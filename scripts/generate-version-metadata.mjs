import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const root = path.resolve(import.meta.dirname, '..');
const packagePath = path.join(root, 'package.json');
const lockPath = path.join(root, 'pnpm-lock.yaml');
const sidecarPath = path.join(root, 'services', 'science', 'cortexlume_science', '_build_version.py');

const packageJson = JSON.parse(await readFile(packagePath, 'utf8'));
if (typeof packageJson.version !== 'string' || !/^\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.-]+)?$/.test(packageJson.version)) {
  throw new Error('Root package.json must contain a valid product version.');
}
const lockBytes = await readFile(lockPath);
const dependencyLockSha256 = createHash('sha256').update(lockBytes).digest('hex');
let gitCommit = process.env.GITHUB_SHA?.trim() || '';
if (!gitCommit) {
  try {
    gitCommit = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8' }).trim();
  } catch {
    gitCommit = 'unknown';
  }
}
if (!/^[0-9a-f]{40}$/i.test(gitCommit)) gitCommit = 'unknown';

const quote = (value) => JSON.stringify(value);
const output = `"""Build metadata generated from the repository root package.json.\n\nDo not edit this file manually; run scripts/generate-version-metadata.mjs.\n"""\n\nPRODUCT_VERSION = ${quote(packageJson.version)}\nAPPLICATION_VERSION = PRODUCT_VERSION\nSIDECAR_PACKAGE_VERSION = PRODUCT_VERSION\nSCIENCE_API_VERSION = "1"\nGIT_COMMIT = ${quote(gitCommit)}\nDEPENDENCY_LOCK_SHA256 = ${quote(dependencyLockSha256)}\n`;
await writeFile(sidecarPath, output, 'utf8');
console.log(JSON.stringify({
  applicationVersion: packageJson.version,
  sidecarPackageVersion: packageJson.version,
  scienceApiVersion: '1',
  gitCommit,
  dependencyLockSha256,
  generated: path.relative(root, sidecarPath),
}));
